/**
* Host half: log the resolved configuration, bridge it to the browser half,
* register the settings namespace, and expose the package's version line plus
* the one-click profile update.
*
* The web boot graph carries no per-entry config, so the validated value is
* injected into every served index response as a boot global the client entry
* reads at apply time. Preferences take the opposite route: the namespace is
* registered here and the browser binds it through `settingsScope`.
* @param ctx - Host context carrying the web server service when composed.
* @param config - Schema-validated configuration with defaults filled.
*/
function apply(ctx, config) {
	console.log(`[${STREAM_PACKAGE_NAME}] plugin loaded! mode=${config.mode} preset=${config.preset} seed=${config.revealCharsPerSec}cps scroll=${config.scrollSpeedPxPerSec}px/s maxScroll=${config.maxScrollSpeedPxPerSec}px/s`);
	ctx.inject(["webServer"], (httpCtx) => {
		httpCtx.effect(() => httpCtx.webServer.tapIndex((html) => injectStreamConfig(html, config)), "dsh-smooth-stream: boot config bridge");
	});
	ctx.inject(["settings"], (settingsCtx) => {
		settingsCtx.settings.register(STREAM_SETTINGS_NS, StreamSettingsSchema, { applies: "live" });
		settingsCtx.inject(["connection"], (connectionCtx) => {
			let upgrade;
			const info = () => {
				const installation = inspectProfileInstallation(connectionCtx.baseUrl, STREAM_PACKAGE_NAME);
				return {
					version: STREAM_PACKAGE_VERSION,
					installation: installation.kind,
					canUpgrade: installation.kind === "npm"
				};
			};
			const handle = async (endpoint) => {
				if (endpoint === STREAM_RPC.info) return {
					ok: true,
					value: info()
				};
				if (endpoint === STREAM_RPC.upgrade) {
					const installation = inspectProfileInstallation(connectionCtx.baseUrl, STREAM_PACKAGE_NAME);
					if (installation.kind !== "npm") return {
						ok: false,
						error: {
							code: "internal",
							message: "smooth-stream is not an npm profile dependency",
							details: {}
						}
					};
					if (upgrade !== void 0) return {
						ok: false,
						error: {
							code: "internal",
							message: "smooth-stream update is already running",
							details: {}
						}
					};
					upgrade = updateNpmProfilePackage(installation.profileDir, STREAM_PACKAGE_NAME);
					try {
						await upgrade;
					} catch {
						return {
							ok: false,
							error: {
								code: "internal",
								message: "smooth-stream update failed",
								details: {}
							}
						};
					} finally {
						upgrade = void 0;
					}
					return {
						ok: true,
						value: { restartRequired: true }
					};
				}
				return {
					ok: false,
					error: {
						code: "internal",
						message: `unknown smooth-stream endpoint ${JSON.stringify(endpoint)}`,
						details: {}
					}
				};
			};
			connectionCtx.effect(() => connectionCtx.connection.rpc.handle(STREAM_RPC_CHANNEL, handle), "dsh-smooth-stream: plugin info RPC");
		});
	});
}
