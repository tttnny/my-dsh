/**
 * 把字典交给宿主。命名空间与键集在这里声明的类型同时是座位 `t` 的契约。
 * @param ctx - 客户端上下文（`locale` 由 inject 声明）。
 */
export function apply(ctx: {
  effect(factory: () => () => void, label?: string): unknown;
  locale: { register(ns: string, dictionaries: unknown): () => void };
}): void {
  ctx.effect(() => ctx.locale.register(NS, { zh, en }), 'dsh-subagent-judge-dispatch: dictionaries');
}

/** 本命名空间全部键的类型，座位上的 `t` 按它做键检查。 */
export type JudgeDispatchLocaleKey = keyof typeof en;

