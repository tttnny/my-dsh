/**
 * Locale bundles for the dsh-a6api card inside the shared 「API中转」 page.
 *
 * `zh` is the key-set source of truth; `en` carries the same keys. Only
 * product-visible copy lives here — model ids, URLs, `code` payloads, log
 * output and upstream-supplied merchant text stay outside the dictionary.
 */
import type { TranslateNS } from '@deepseek-ai/dsh-client-ui-slots';

/** Locale namespace owned by this plugin's settings card. */
export const NS = 'settings.a6api';

/** Translate function bound to this plugin's namespace. */
export type A6apiT = TranslateNS<typeof NS>;

/**
 * Translator over the Chinese source dictionary. The settings card always
 * receives the seat-bound `t`; this default exists only for the components the
 * composer dock popup shares (`MerchantCard`, `PricePill`, `MarketPill`) —
 * that registration declares no locale namespace and is outside this change.
 * `{name}` placeholders follow the locale runtime's template contract.
 */
export const dictionaryT = ((key: string, params?: Record<string, unknown>) => {
  const template = zh[key as A6apiLocaleKey];
  if (params === undefined) return template;
  return template.replace(/\{(\w+)\}/g, (match: string, name: string) =>
    name in params ? String(params[name]) : match,
  );
}) as A6apiT;

